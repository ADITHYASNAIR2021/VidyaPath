'use client';

import { useEffect, useMemo, useRef, useState } from 'react';
import Link from 'next/link';
import clsx from 'clsx';
import { CheckCircle2, ClipboardCheck, Clock, Loader2, RotateCcw, XCircle } from 'lucide-react';
import { BOARD_CHAPTERS } from '@/lib/data';
import { useStudentProfileStore, useStudyActivityStore } from '@/lib/store';
import type { MCQItem } from '@/lib/ai/validators';

type Phase = 'setup' | 'loading' | 'exam' | 'results';

interface MockAttempt {
  id: string;
  subject: string;
  classLevel: 10 | 12;
  score: number;
  total: number;
  takenAt: string;
}

const HISTORY_KEY = 'vidyapath-mock-exams';
const MAX_CHAPTERS_PER_PAPER = 8;

function readHistory(): MockAttempt[] {
  try {
    const raw = localStorage.getItem(HISTORY_KEY);
    const parsed = raw ? (JSON.parse(raw) as MockAttempt[]) : [];
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

function writeHistory(history: MockAttempt[]) {
  try {
    localStorage.setItem(HISTORY_KEY, JSON.stringify(history.slice(0, 30)));
  } catch {
    // Storage unavailable (private mode) — results still show for this attempt.
  }
}

function formatClock(totalSeconds: number): string {
  const safe = Math.max(0, totalSeconds);
  const minutes = Math.floor(safe / 60);
  const seconds = safe % 60;
  return `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
}

function sampleChapters<T>(items: T[], limit: number): T[] {
  if (items.length <= limit) return items;
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, limit);
}

/**
 * Timed mock exam — generated by AI from NCERT/PYQ context and graded in the browser.
 * No account: the paper, answers and score history stay on this device.
 */
export default function MockExamPage() {
  const profileClassLevel = useStudentProfileStore((state) => state.classLevel);
  const recordActivity = useStudyActivityStore((state) => state.recordActivity);

  const [phase, setPhase] = useState<Phase>('setup');
  const [classLevel, setClassLevel] = useState<10 | 12>(12);
  const [subject, setSubject] = useState('');
  const [questionCount, setQuestionCount] = useState(15);
  const [durationMinutes, setDurationMinutes] = useState(20);
  const [error, setError] = useState('');
  const [questions, setQuestions] = useState<MCQItem[]>([]);
  const [answers, setAnswers] = useState<Array<number | null>>([]);
  const [current, setCurrent] = useState(0);
  const [secondsLeft, setSecondsLeft] = useState(0);
  const [history, setHistory] = useState<MockAttempt[]>([]);
  const submittedRef = useRef(false);

  useEffect(() => {
    if (profileClassLevel) setClassLevel(profileClassLevel);
  }, [profileClassLevel]);

  useEffect(() => {
    setHistory(readHistory());
  }, []);

  const subjects = useMemo(
    () => Array.from(new Set(BOARD_CHAPTERS.filter((ch) => ch.classLevel === classLevel).map((ch) => ch.subject))),
    [classLevel]
  );

  useEffect(() => {
    if (!subjects.includes(subject as (typeof subjects)[number])) setSubject(subjects[0] ?? '');
  }, [subject, subjects]);

  const score = useMemo(
    () => questions.reduce((sum, question, index) => (answers[index] === question.answer ? sum + 1 : sum), 0),
    [answers, questions]
  );

  function finishExam() {
    if (submittedRef.current) return;
    submittedRef.current = true;
    setPhase('results');
    recordActivity();
    const attempt: MockAttempt = {
      id: `${Date.now()}`,
      subject,
      classLevel,
      score: questions.reduce((sum, question, index) => (answers[index] === question.answer ? sum + 1 : sum), 0),
      total: questions.length,
      takenAt: new Date().toISOString(),
    };
    const next = [attempt, ...readHistory()];
    writeHistory(next);
    setHistory(next);
  }

  useEffect(() => {
    if (phase !== 'exam') return;
    if (secondsLeft <= 0) {
      finishExam();
      return;
    }
    const timer = setTimeout(() => setSecondsLeft((value) => value - 1), 1000);
    return () => clearTimeout(timer);
    // finishExam reads the latest answers via state at call time.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [phase, secondsLeft]);

  async function startExam() {
    const chapterIds = sampleChapters(
      BOARD_CHAPTERS.filter((ch) => ch.classLevel === classLevel && ch.subject === subject),
      MAX_CHAPTERS_PER_PAPER
    ).map((ch) => ch.id);
    if (chapterIds.length === 0) {
      setError('No chapters found for this subject.');
      return;
    }

    setError('');
    setPhase('loading');
    try {
      const response = await fetch('/api/adaptive-test', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ classLevel, subject, chapterIds, questionCount, difficultyMix: 'board-mixed', mode: 'mock-exam' }),
      });
      const payload = await response.json().catch(() => null);
      if (!response.ok) {
        setError(payload?.message || 'Could not create the mock exam. Please try again.');
        setPhase('setup');
        return;
      }
      const data = payload && typeof payload === 'object' && 'data' in payload ? payload.data : payload;
      const generated: MCQItem[] = Array.isArray(data?.questions)
        ? data.questions.filter(
            (item: MCQItem) => item && typeof item.question === 'string' && Array.isArray(item.options) && item.options.length >= 2
          )
        : [];
      if (generated.length === 0) {
        setError('The AI could not build a paper right now. Please try again in a minute.');
        setPhase('setup');
        return;
      }
      submittedRef.current = false;
      setQuestions(generated);
      setAnswers(generated.map(() => null));
      setCurrent(0);
      setSecondsLeft(durationMinutes * 60);
      setPhase('exam');
    } catch {
      setError('Check your internet connection and try again.');
      setPhase('setup');
    }
  }

  if (phase === 'exam') {
    const question = questions[current];
    const answeredCount = answers.filter((value) => value !== null).length;
    return (
      <div className="min-h-screen bg-[#FDFAF6] px-4 py-6 md:px-6">
        <div className="mx-auto max-w-3xl">
          <div className="mb-4 flex flex-wrap items-center justify-between gap-3">
            <div className="text-sm font-semibold text-navy-700">
              Class {classLevel} {subject} · Question {current + 1} of {questions.length}
            </div>
            <div
              className={clsx(
                'inline-flex items-center gap-1.5 rounded-xl px-3 py-1.5 text-sm font-bold',
                secondsLeft < 60 ? 'bg-rose-100 text-rose-700' : 'bg-navy-700 text-white'
              )}
              role="timer"
              aria-live="off"
            >
              <Clock className="h-4 w-4" /> {formatClock(secondsLeft)}
            </div>
          </div>

          <div className="rounded-2xl border border-[#E8E4DC] bg-white p-5 shadow-sm">
            <p className="text-base font-semibold leading-relaxed text-navy-700">{question.question}</p>
            <div className="mt-4 space-y-2">
              {question.options.map((option, optionIndex) => (
                <button
                  key={optionIndex}
                  type="button"
                  onClick={() =>
                    setAnswers((prev) => prev.map((value, index) => (index === current ? optionIndex : value)))
                  }
                  className={clsx(
                    'w-full rounded-xl border px-4 py-3 text-left text-sm transition-colors',
                    answers[current] === optionIndex
                      ? 'border-saffron-500 bg-saffron-50 font-semibold text-saffron-800'
                      : 'border-gray-200 hover:bg-gray-50'
                  )}
                >
                  <span className="mr-2 font-bold">{String.fromCharCode(65 + optionIndex)}.</span>
                  {option}
                </button>
              ))}
            </div>
          </div>

          <div className="mt-4 flex flex-wrap gap-1.5" aria-label="Question navigator">
            {questions.map((_, index) => (
              <button
                key={index}
                type="button"
                onClick={() => setCurrent(index)}
                aria-label={`Go to question ${index + 1}`}
                className={clsx(
                  'h-8 w-8 rounded-lg text-xs font-bold',
                  index === current
                    ? 'bg-navy-700 text-white'
                    : answers[index] !== null
                      ? 'bg-emerald-100 text-emerald-800'
                      : 'bg-white text-[#6D6A7C] border border-gray-200'
                )}
              >
                {index + 1}
              </button>
            ))}
          </div>

          <div className="mt-5 flex items-center justify-between gap-3">
            <button
              type="button"
              disabled={current === 0}
              onClick={() => setCurrent((value) => Math.max(0, value - 1))}
              className="rounded-xl border border-gray-200 bg-white px-4 py-2 text-sm font-semibold text-navy-700 disabled:opacity-40"
            >
              Previous
            </button>
            {current < questions.length - 1 ? (
              <button
                type="button"
                onClick={() => setCurrent((value) => Math.min(questions.length - 1, value + 1))}
                className="rounded-xl bg-saffron-500 px-4 py-2 text-sm font-semibold text-white hover:bg-saffron-600"
              >
                Next
              </button>
            ) : (
              <button
                type="button"
                onClick={finishExam}
                className="rounded-xl bg-emerald-600 px-4 py-2 text-sm font-semibold text-white hover:bg-emerald-700"
              >
                Submit ({answeredCount}/{questions.length} answered)
              </button>
            )}
          </div>
        </div>
      </div>
    );
  }

  if (phase === 'results') {
    const pct = questions.length > 0 ? Math.round((score / questions.length) * 100) : 0;
    return (
      <div className="min-h-screen bg-[#FDFAF6] px-4 py-8 md:px-6">
        <div className="mx-auto max-w-3xl">
          <div className="rounded-2xl border border-[#E8E4DC] bg-white p-6 text-center shadow-sm">
            <p className="text-sm font-semibold text-[#6D6A7C]">Class {classLevel} {subject} mock exam</p>
            <p className="mt-2 font-fraunces text-4xl font-bold text-navy-700">
              {score} / {questions.length}
            </p>
            <p className="mt-1 text-sm text-[#6D6A7C]">{pct}% · saved on this device</p>
            <div className="mt-4 flex flex-wrap justify-center gap-2">
              <button
                type="button"
                onClick={() => setPhase('setup')}
                className="inline-flex items-center gap-1.5 rounded-xl bg-saffron-500 px-4 py-2 text-sm font-semibold text-white hover:bg-saffron-600"
              >
                <RotateCcw className="h-4 w-4" /> New mock exam
              </button>
              <Link href="/revision" className="rounded-xl border border-gray-200 px-4 py-2 text-sm font-semibold text-navy-700 hover:bg-gray-50">
                Plan revision
              </Link>
            </div>
          </div>

          <h2 className="mt-6 font-fraunces text-xl font-bold text-navy-700">Answer review</h2>
          <ol className="mt-3 space-y-3">
            {questions.map((question, index) => {
              const correct = answers[index] === question.answer;
              return (
                <li key={index} className="rounded-2xl border border-[#E8E4DC] bg-white p-4">
                  <div className="flex items-start gap-2">
                    {correct ? (
                      <CheckCircle2 className="mt-0.5 h-5 w-5 shrink-0 text-emerald-600" aria-label="Correct" />
                    ) : (
                      <XCircle className="mt-0.5 h-5 w-5 shrink-0 text-rose-600" aria-label="Incorrect" />
                    )}
                    <div className="min-w-0">
                      <p className="text-sm font-semibold text-navy-700">
                        {index + 1}. {question.question}
                      </p>
                      <p className="mt-1 text-xs text-[#6D6A7C]">
                        Your answer:{' '}
                        {answers[index] === null ? 'Not answered' : question.options[answers[index] as number]}
                        {!correct && <> · Correct: {question.options[question.answer]}</>}
                      </p>
                      {question.explanation && (
                        <p className="mt-2 text-xs leading-relaxed text-[#4A4A6A]">{question.explanation}</p>
                      )}
                    </div>
                  </div>
                </li>
              );
            })}
          </ol>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-[#FDFAF6] px-4 py-8 md:px-6">
      <div className="mx-auto max-w-xl">
        <div className="rounded-2xl border border-[#E8E4DC] bg-white p-6 shadow-sm">
          <div className="flex items-center gap-2">
            <ClipboardCheck className="h-6 w-6 text-saffron-500" />
            <h1 className="font-fraunces text-2xl font-bold text-navy-700">Mock Exam</h1>
          </div>
          <p className="mt-1 text-sm text-[#6D6A7C]">
            A timed, board-style MCQ paper built by AI from NCERT and previous-year questions. No login needed.
          </p>

          {error && (
            <div className="mt-4 rounded-xl border border-rose-200 bg-rose-50 px-3 py-2 text-sm text-rose-700" role="alert">
              {error}
            </div>
          )}

          <div className="mt-5 grid gap-4">
            <label className="text-sm font-medium text-navy-700">
              Class
              <select
                value={classLevel}
                onChange={(event) => setClassLevel(Number(event.target.value) === 10 ? 10 : 12)}
                className="mt-1 w-full rounded-xl border border-gray-200 px-3 py-2 text-sm"
              >
                <option value={10}>Class 10</option>
                <option value={12}>Class 12</option>
              </select>
            </label>

            <label className="text-sm font-medium text-navy-700">
              Subject
              <select
                value={subject}
                onChange={(event) => setSubject(event.target.value)}
                className="mt-1 w-full rounded-xl border border-gray-200 px-3 py-2 text-sm"
              >
                {subjects.map((item) => (
                  <option key={item} value={item}>
                    {item}
                  </option>
                ))}
              </select>
            </label>

            <div className="grid grid-cols-2 gap-3">
              <label className="text-sm font-medium text-navy-700">
                Questions
                <select
                  value={questionCount}
                  onChange={(event) => setQuestionCount(Number(event.target.value))}
                  className="mt-1 w-full rounded-xl border border-gray-200 px-3 py-2 text-sm"
                >
                  {[10, 15, 20, 25, 30].map((count) => (
                    <option key={count} value={count}>
                      {count}
                    </option>
                  ))}
                </select>
              </label>
              <label className="text-sm font-medium text-navy-700">
                Minutes
                <select
                  value={durationMinutes}
                  onChange={(event) => setDurationMinutes(Number(event.target.value))}
                  className="mt-1 w-full rounded-xl border border-gray-200 px-3 py-2 text-sm"
                >
                  {[10, 15, 20, 30, 45, 60].map((minutes) => (
                    <option key={minutes} value={minutes}>
                      {minutes}
                    </option>
                  ))}
                </select>
              </label>
            </div>
          </div>

          <button
            type="button"
            onClick={startExam}
            disabled={phase === 'loading' || !subject}
            className="mt-6 inline-flex w-full items-center justify-center gap-2 rounded-xl bg-saffron-500 px-4 py-2.5 text-sm font-semibold text-white hover:bg-saffron-600 disabled:opacity-60"
          >
            {phase === 'loading' ? (
              <>
                <Loader2 className="h-4 w-4 animate-spin" /> Building your paper…
              </>
            ) : (
              'Start mock exam'
            )}
          </button>
        </div>

        {history.length > 0 && (
          <div className="mt-6 rounded-2xl border border-[#E8E4DC] bg-white p-5">
            <h2 className="font-fraunces text-lg font-bold text-navy-700">Past attempts (this device)</h2>
            <ul className="mt-3 divide-y divide-gray-100">
              {history.slice(0, 8).map((attempt) => (
                <li key={attempt.id} className="flex items-center justify-between py-2 text-sm">
                  <span className="text-navy-700">
                    Class {attempt.classLevel} {attempt.subject}
                    <span className="ml-2 text-xs text-[#8A8AAA]">{new Date(attempt.takenAt).toLocaleDateString()}</span>
                  </span>
                  <span className="font-semibold text-navy-700">
                    {attempt.score}/{attempt.total}
                  </span>
                </li>
              ))}
            </ul>
          </div>
        )}
      </div>
    </div>
  );
}
